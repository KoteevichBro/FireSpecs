def normalize_language(code: str | None) -> str:
    if not code:
        return DEFAULT_LANGUAGE
    code = code.lower().split("-")[0].split("_")[0]
    if code in SUPPORTED_LANGUAGES:
        return code
    return DEFAULT_LANGUAGE


class Translator:
    def __init__(self, language: str | None = None):
        self.language = normalize_language(language)

    def set_language(self, language: str) -> None:
        self.language = normalize_language(language)

    def translate(self, key: str, **kwargs) -> str:
        catalog = _MESSAGES.get(self.language) or _MESSAGES[DEFAULT_LANGUAGE]
        text = catalog.get(key) or _MESSAGES[DEFAULT_LANGUAGE].get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, ValueError):
                return text
        return text

    def tr_dict(self, mapping: dict[str, object]) -> dict[str, object]:
        return {self.translate(key): value for key, value in mapping.items()}
